/** WordPress gettext catalogue; the block language stays independent of the site locale. */
final class Orthocal_I18n {
    private static $language = null;
    private static $catalogues = [];
    static function with_language($language, $callback) {
        $previous=self::$language;
        self::$language=$language;
        try { return $callback(); } finally { self::$language=$previous; }
    }
    static function text($text) {
        $catalog=self::catalogue(self::$language);
        return $catalog[$text]??$text;
    }
    static function catalogue($language=null) {
        $locale=$language===null?determine_locale():(['ru'=>'ru_RU','cu'=>'ru_RU','de'=>'de_DE','uk'=>'uk','pl'=>'pl_PL'][$language]??'ru_RU');
        $cacheKey=($language===null?'site:':'block:').$locale;
        if(isset(self::$catalogues[$cacheKey]))return self::$catalogues[$cacheKey];
        $catalog=self::strings();
        // Core MO reader allows several block languages on the same page.
        if(!class_exists('MO'))require_once ABSPATH.WPINC.'/pomo/mo.php';
        $filename='georg-kloster-calendar-workshop-'.$locale.'.mo';
        $paths=[__DIR__.'/../languages/'.$filename];
        if($language!==null)$paths[]=WP_LANG_DIR.'/plugins/'.$filename;
        $siteCatalog=$catalog;
        if($language!==null)$catalog=array_combine(array_keys($catalog),array_keys($catalog));
        foreach($paths as $path) {
            $mo=new MO();
            if(!is_readable($path)||!$mo->import_from_file($path))continue;
            foreach($catalog as $original=>$translated)if(isset($mo->entries[$original]))$catalog[$original]=$mo->translate($original);
        }
        if($language===null)foreach($siteCatalog as $original=>$translated)if($translated!==$original)$catalog[$original]=$translated;
        return self::$catalogues[$cacheKey]=$catalog;
    }
